"""Render a run's directive as Markdown (single implementation shared by API and UI)."""

from __future__ import annotations

from server.db.models import Run
from server.schemas.api import RunResult


def _md(text: str) -> str:
    return text.replace("\r", "").replace("<", "&lt;")


def directive_markdown(run: Run) -> str:
    result = RunResult.model_validate(run.result or {})
    d, c = result.directive, result.confidence
    lines = [
        f"# {_md(d.title) if d else 'NEXUS Directive'}",
        "",
        f"**Mission:** {_md(run.mission)}  ",
        f"**Mode:** {run.mode}  ",
    ]
    if run.refinement:
        lines.append(f"**Refinement:** {_md(run.refinement)}  ")
    lines.append(f"**Run:** `{run.id}` · **Status:** {run.status} · **Decision:** {run.decision_status}  ")
    if c:
        lines.append(f"**Confidence:** {c.score}/100 — {c.explanation}  ")
    if run.simulated:
        lines += ["", "> ⚠️ Generated by the offline simulator. Template-grade output; do not use for real decisions."]
    if not d:
        return "\n".join([*lines, "", "_No directive was produced._", ""])
    lines += ["", "## Decision", "", _md(d.decision), "", "## Rationale", "", _md(d.rationale), "", "## Tradeoffs", ""]
    lines += [f"- {_md(t)}" for t in d.tradeoffs]
    lines += ["", "## Execution plan", ""]
    for i, ph in enumerate(d.phases, 1):
        lines += [f"### Phase {i}: {_md(ph.name)}", "", f"**Goal:** {_md(ph.goal)}", ""]
        lines += [f"- {_md(a)}" for a in ph.actions]
        lines += ["", f"**Exit criteria:** {_md(ph.exit_criteria)}", ""]
    lines += ["## KPIs", "", "| KPI | Target | Measurement |", "|---|---|---|"]
    lines += [f"| {_md(k.name)} | {_md(k.target)} | {_md(k.measurement)} |" for k in d.kpis]
    lines += ["", "## Risks", "", "| Risk | Severity | Owner | Mitigation |", "|---|---|---|---|"]
    lines += [f"| {_md(r.risk)} | {r.severity.value} | {_md(r.owner)} | {_md(r.mitigation)} |" for r in d.risks]
    lines += ["", "## Next actions", ""] + [f"- [ ] {_md(a)}" for a in d.next_actions]
    sources = sorted(
        {
            (e.source_title or e.url or "", e.url)
            for rep in result.reports.values()
            for f in rep.findings
            for e in f.evidence
            if e.url
        }
    )
    if sources:
        lines += ["", "## Sources", ""] + [f"- [{_md(t)}]({u})" for t, u in sources]
    lines += [
        "",
        "---",
        f"_Prompt versions: {', '.join(f'{k}={v}' for k, v in sorted((run.prompt_versions or {}).items()))}_",
        "",
    ]
    return "\n".join(lines)
